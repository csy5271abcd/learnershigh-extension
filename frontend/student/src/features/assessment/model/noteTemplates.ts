// 내용 원칙 (2026-10-27 사용자 요청으로 보강):
// - templateId·이름·이모지 소제목은 그대로 둔다.
// - 소제목마다 짧은 안내(💡), 생각할 질문, 빈 칸의 예시(흐린 안내 문구 = placeholder), 표·체크리스트 뼈대, 참고자료 자리를 둔다.
// - 학생의 결과·결론·세특 문장을 대신 쓰지 않는다. 예시는 "어떤 식으로 적는지"만 보여 준다.
// - 안내 문구(placeholder)는 빈 칸에만 흐리게 보이고 노트 글로 저장되지 않는다. 💡 안내 블록과 체크 항목은 필요 없으면 지운다.

export type NoteTemplateCategory = '기본' | '보고서' | '데이터·실험' | '발표·토론' | '글쓰기' | '활동'

export interface NoteTemplate {
  templateId: string
  name: string
  category: NoteTemplateCategory
  blocks: NoteBlock[]
}

/** 템플릿 조각 */
type Part =
  /** 이모지 소제목 (원래 템플릿 소제목 그대로) */
  | { h: string }
  /** 💡 짧은 안내 (지워도 되는 도움말) */
  | { guide: string }
  /** 빈 본문 + 흐린 예시·질문 (저장되지 않는 자리 표시) */
  | { write: string }
  /** 빈 글머리 항목 + 흐린 예시 */
  | { item: string }
  /** 빈 번호 항목 + 흐린 예시 */
  | { step: string }
  /** 점검 항목 (체크리스트) */
  | { check: string }
  /** 표 뼈대 (첫 행 머리글) */
  | { table: string[][] }
  /** 자료함 참고자료 연결 자리 */
  | { ref: true }

function block(id: string, type: string, text: string, attrs?: NoteBlockAttrs): NoteBlock {
  return attrs ? { blockId: id, type, text, attrs } : { blockId: id, type, text }
}

const define = (templateId: string, name: string, category: NoteTemplateCategory, parts: Part[]): NoteTemplate => ({
  templateId,
  name,
  category,
  blocks: parts.map((part, index) => {
    const id = `${templateId}-b${String(index + 1).padStart(2, '0')}`
    if ('h' in part) return block(id, 'HEADING', part.h)
    if ('guide' in part) return block(id, 'CALLOUT', part.guide, { emoji: '💡' })
    if ('write' in part) return block(id, 'PARAGRAPH', '', { placeholder: part.write })
    if ('item' in part) return block(id, 'BULLET', '', { placeholder: part.item })
    if ('step' in part) return block(id, 'NUMBERED', '', { placeholder: part.step })
    if ('check' in part) return block(id, 'CHECKLIST', part.check, { checked: false })
    if ('table' in part) return block(id, 'TABLE', '', { rows: part.table })
    return block(id, 'RESOURCE_LINK', '')
  }),
})

